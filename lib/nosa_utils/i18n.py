    def __init__(self, language='en-GB'):
        """Initialize localization with specified language"""
        if language not in self.LANGUAGES:
            language = 'en-GB'  # Default to British English
        self.language = language
        self.strings = self.LANGUAGES[language]
    
    def get(self, key, default=None):
        """Get localized string"""
        return self.strings.get(key, default or key)
    
    def t(self, key, default=None):
        """Shortcut for get()"""
        return self.get(key, default)
    
    def set_language(self, language):
        if language in self.LANGUAGES:
            self.language = language
            self.strings = self.LANGUAGES[language]
            
    @classmethod
    def get_available_languages(cls):
        return list(cls.LANGUAGES.keys())
